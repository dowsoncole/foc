/**
  * @brief This function handles TIM6 global interrupt.
  *
  * 1 s driver-monitor heartbeat. This ISR performs no I2C transfer: it only
  * raises a flag that the main-loop task consumes.
  */
void TIM6_DAC_IRQHandler(void)
{
  HAL_TIM_IRQHandler(&htim6);

  /* Deadline enforcement for a running TIM1 verification. Does nothing while no
     verification is armed. */
  Tim1PwmVerify_TickIsr();
}

/**
  * @brief This function handles TIM1 capture/compare interrupt.
  *
  * Reached from the channel 4 compare, which MX_TIM1_Init() places just before
  * the update event. This is the sampling instant of the current loop:
  * start the injected ADC conversion here and let the end-of-conversion ISR run
  * the regulator. Nothing else may be added to this path - it runs at the PWM
  * frequency.
  */
void TIM1_CC_IRQHandler(void)
{
  HAL_TIM_IRQHandler(&htim1);
}

/**
  * @brief This function handles TIM1 update interrupt.
  *
  * The period boundary, once per PWM period thanks to the repetition counter.
  * HAL_TIM_IRQHandler() dispatches it to HAL_TIM_PeriodElapsedCallback(), which
  * is shared with the TIM6 heartbeat and therefore filters on the instance: this
  * event currently costs one comparison and is otherwise unused. It is enabled
  * from the start because the current loop needs a period boundary that does not
  * depend on the ADC finishing.
  */
void TIM1_UP_TIM16_IRQHandler(void)
{
  HAL_TIM_IRQHandler(&htim1);
}
