"""Extract the supplied 300 Hz / 1..15 Hz literal command table, read-only XLSX.

No formula recalculation, inferred waveform, interpolation, or XLSX edits.
"""
import argparse
import hashlib
import json
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile


def extract(path):
    ns={'s':'http://schemas.openxmlformats.org/spreadsheetml/2006/main',
        'r':'http://schemas.openxmlformats.org/officeDocument/2006/relationships'}
    with ZipFile(path) as z:
        book=ET.fromstring(z.read('xl/workbook.xml'))
        sheets=book.find('s:sheets',ns)
        target=next(s for s in sheets if s.get('name')=='PWM table due 1 sec')
        rels=ET.fromstring(z.read('xl/_rels/workbook.xml.rels'))
        rel=next(r for r in rels if r.get('Id')==target.get('{'+ns['r']+'}id'))
        source=rel.get('Target').lstrip('/')
        if not source.startswith('xl/'):source='xl/'+source
        root=ET.fromstring(z.read(source))
        cells={c.get('r'):c for c in root.findall('.//s:sheetData/s:row/s:c',ns)}
        def integer(cell):
            c=cells[cell]
            if c.find('s:f',ns) is not None:raise ValueError(f'{cell}: literal required')
            value=float(c.find('s:v',ns).text)
            if not value.is_integer():raise ValueError(f'{cell}: noninteger command')
            return int(value)
        table=[]
        for col,f in zip('BCDEFGHIJKLMNOP',range(1,16)):
            if integer(col+'1')!=f:raise ValueError('Frequency header mismatch')
            row=[integer(f'{col}{r}') for r in range(2,302)]
            if any(not 1500<=v<=1520 for v in row):raise ValueError('PWM outside declared envelope')
            table.append([v-1500 for v in row])
    return table


def generate(source,header,manifest):
    table=extract(source)
    digest=hashlib.sha256(Path(source).read_bytes()).hexdigest()
    text=['/* Generated by import_customer_pwm_table.py; do not hand-edit.',
          '   Source: 客户需求PWM给定方式.xlsx, PWM table due 1 sec!B2:P301.',
          f'   XLSX SHA256: {digest}',
          '   300 frames/s, each row = one second at 1..15 Hz. Values = us - 1500. */',
          '#ifndef CUSTOMER_PWM_TABLE_H','#define CUSTOMER_PWM_TABLE_H',
          '#include <stdint.h>','static const uint8_t customer_pwm_table[15][300] = {']
    for f,row in enumerate(table,1):
        text.append(f'  {{ /* {f} Hz */')
        text += ['    '+','.join(str(x) for x in row[i:i+30])+',' for i in range(0,300,30)]
        text.append('  },')
    text+=['};','#endif','']
    Path(header).write_text('\n'.join(text),encoding='utf-8')
    evidence=dict(source_name=Path(source).name,source_sha256=digest,
                  sheet='PWM table due 1 sec',range='B2:P301',carrier_hz=300,
                  frequencies_hz=list(range(1,16)),frames_per_second=300,
                  source_commands_sha256=hashlib.sha256(bytes(v for row in table for v in row)).hexdigest(),
                  note='Literal commands only. 16..30 Hz are not supplied. No external PWM interface is implemented.')
    Path(manifest).write_text(json.dumps(evidence,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return evidence


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('source',type=Path);p.add_argument('header',type=Path);p.add_argument('manifest',type=Path)
    a=p.parse_args();print(json.dumps(generate(a.source,a.header,a.manifest),ensure_ascii=False,indent=2))
