% Run from repository root. Actual System Identification Toolbox generation.
r=fullfile(fileparts(fileparts(mfilename('fullpath'))),'results');
rng(2409,'twister');
u=idinput(127,'prbs',[0 1],[-1 1]);
assert(numel(u)==127 && all(abs(u)==1));
u_est=uint8(u>0); u_val=circshift(u_est,37);
f=fopen(fullfile(r,'prbs_est_sequence.bin'),'wb'); assert(f>=0); fwrite(f,u_est,'uint8'); fclose(f);
f=fopen(fullfile(r,'prbs_val_sequence.bin'),'wb'); assert(f>=0); fwrite(f,u_val,'uint8'); fclose(f);
save(fullfile(r,'prbs_excitation.mat'),'u','u_est','u_val');
fprintf('PRBS127 generated by idinput, bit time 16 ms, record time 8 ms.\n');
fprintf('Validation is a separate physical run, cyclic shift 37 bits, not independent PRBS spectrum.\n');
