"""Generate/check the inverse fundamental-gain tables; no firmware dependency.

Print a header to stdout; --check validates the committed header.
The reference uses sector dwell times, independent of the C phase-sorting code.
"""
import argparse
import math
from pathlib import Path

LINEAR = 1.0 / math.sqrt(3.0)
SIX_STEP = 2.0 / math.pi
RADIUS_STEPS = 64
HOLD_STEPS = 128
INTEGRATION_STEPS = 8192


def fundamental(radius, hold=None):
    total = 0.0
    for i in range(INTEGRATION_STEPS + 1):
        angle = (math.pi / 3.0) * i / INTEGRATION_STEPS
        t1 = math.sqrt(3.0) * radius * math.sin(math.pi / 3.0 - angle)
        t2 = math.sqrt(3.0) * radius * math.sin(angle)
        if hold is None:
            scale = max(1.0, t1 + t2)
            t1, t2 = t1 / scale, t2 / scale
        else:
            ratio = t2 / (t1 + t2)
            if hold == 1.0:
                ratio = 0.0 if i < INTEGRATION_STEPS / 2 else 1.0
            else:
                ratio = min(1.0, max(0.0, 0.5 + (ratio - 0.5) / (1.0 - hold)))
            t1, t2 = 1.0 - ratio, ratio
        alpha = (2.0 * t1 + t2) / 3.0
        beta = t2 / math.sqrt(3.0)
        value = alpha * math.cos(angle) + beta * math.sin(angle)
        weight = 1 if i in (0, INTEGRATION_STEPS) else (4 if i % 2 else 2)
        total += weight * value
    # (3/pi) * integral over one 60-degree sector, Simpson's rule.
    return total / (3.0 * INTEGRATION_STEPS)


def render():
    radius = [fundamental(LINEAR + (2.0 / 3.0 - LINEAR) * i / RADIUS_STEPS)
              for i in range(RADIUS_STEPS + 1)]
    hold = [fundamental(2.0 / 3.0, i / HOLD_STEPS)
            for i in range(HOLD_STEPS + 1)]
    radius[0] = LINEAR
    hold[0] = radius[-1]
    hold[-1] = SIX_STEP
    for values in (radius, hold):
        assert all(a < b for a, b in zip(values, values[1:])), "Non-monotonic LUT"
    lines = ["/* Generated by FOC/Tools/generate_modulation_lut.py; do not edit. */",
             "#ifndef FOC_MODULATION_LUT_H", "#define FOC_MODULATION_LUT_H", "",
             f"#define FOC_MODULATION_HEXAGON_FUNDAMENTAL {radius[-1]:.10f}f", ""]
    for name, values in (("foc_ovm1_fundamental", radius), ("foc_ovm2_fundamental", hold)):
        lines.append(f"static const float {name}[{len(values)}] =")
        lines.append("{")
        for i in range(0, len(values), 4):
            lines.append("  " + ", ".join(f"{v:.10f}f" for v in values[i:i+4]) + ",")
        lines.extend(["};", ""])
    lines.extend(["#endif", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    header = render()
    if args.check:
        path = Path(__file__).resolve().parents[1] / "Src" / "foc_modulation_lut.h"
        assert path.read_text(encoding="utf-8") == header, "Regenerate LUT header"
        print("Modulation LUT matches the independent dwell-time integration.")
    else:
        print(header, end="")
